// Lumina FX: Saturator. The second insert, to the same bar as the compressor (HANDOFF.md section 4).
// Header-only C++17, no dependencies, no allocation anywhere (all state is fixed arrays); MPC-safe.
//
// WHY THE OVERSAMPLING IS THE WHOLE POINT
//   A waveshaper makes harmonics. At 44.1 kHz a 9 kHz tone driven hard has a 3rd harmonic at 27 kHz: it cannot exist, so it
//   FOLDS BACK to 17 kHz as an inharmonic alias that sounds like grit, not warmth. The cure is to shape at a higher rate and
//   filter before coming back down. This saturator shapes at 4x (2x and 1x selectable) through two polyphase all-pass half-band
//   filters, designed and measured by tools/design_halfband.py:
//       stage A (2x <-> 1x): 103.0 dB stopband, passband ripple 2e-10 dB, 4+4 coefficients
//       stage B (4x <-> 2x): 124.2 dB stopband, passband ripple 2e-12 dB, 2+2 coefficients
//   Round-trip latency is about 5 base-rate samples at 4x (0.1 ms at 48 kHz): latencySamples().
//
// SIGNAL FLOW (per channel)
//   in -> [oversample] -> wet = shape(drive * x + bias) - shape(bias)  -> tone (1-pole low-pass at the oversampled rate)
//      -> mix with the (filtered, unshaped) dry AT THE OVERSAMPLED RATE, so dry and wet share one phase response
//      -> auto gain / output trim -> [decimate] -> DC blocker (8 Hz) -> out.
//   Curves (all exact formulas, all measured in tests/test_saturator.cpp against numerically integrated harmonics):
//       TUBE   tanh(x)                       odd harmonics, and even ones when bias != 0 (asymmetry)
//       TAPE   x / (1 + |x|^3)^(1/3)         softer onset, sharper knee than tanh
//       DIODE  1 - e^-x above 0, -0.8 (1 - e^x) below   built-in asymmetry: even and odd harmonics
//   Bias shifts the operating point before the curve (asymmetry => 2nd harmonic); the static offset is subtracted, the
//   remaining DC is removed by the blocker. AUTO GAIN keeps a half-scale peak at half scale whatever the drive.
//   Bypass leaves the buffer untouched (bit exact). Non-finite input is replaced by 0. Recursive state is double and flushed
//   below 1e-30. Drive, mix and output are smoothed (5 ms) so moving them never zippers.
#pragma once
#include <algorithm>
#include <cmath>
#include <cstddef>

namespace lumina::fx {

struct SatParams {
    float driveDb  = 12.0f;     // 0 .. 36
    int   type     = 0;         // 0 TUBE, 1 TAPE, 2 DIODE
    float bias     = 0.0f;      // -1 .. 1 (asymmetry)
    float toneHz   = 20000.0f;  // 1000 .. 20000; >= 19900 = off
    float mix      = 1.0f;      // 0 dry .. 1 wet
    float outputDb = 0.0f;      // -24 .. 12
    bool  autoGain = true;
    int   oversample = 4;       // 1, 2 or 4
    bool  bypass   = false;
};

namespace satdetail {
// generated by tools/design_halfband.py (do not edit by hand)
constexpr double kStageAA0[4] = { 0.037134797822863046, 0.28010395543920652, 0.58312786676616468, 0.8339490956157759 };
constexpr double kStageAA1[4] = { 0.13860449082661652, 0.43481838440552889, 0.71604341357878765, 0.94408213862745949 };
constexpr double kStageBA0[2] = { 0.039970500326465416, 0.38096296263141299 };
constexpr double kStageBA1[2] = { 0.16256910235427291, 0.73750660611906949 };
// DC group delay of each stage, in samples at that stage's high rate (measured by the design script)
constexpr double kGdA = 3.689, kGdB = 2.743;

inline void flush(double& v) { if (std::fabs(v) < 1e-30) v = 0.0; }

/// First-order all-pass sections in series: (a + z^-1) / (1 + a z^-1), transposed direct form II.
template <int N> struct Chain {
    double a[N] = {}, s[N] = {};
    void set(const double* coefs) { for (int i = 0; i < N; ++i) a[i] = coefs[i]; }
    double tick(double x) {
        for (int i = 0; i < N; ++i) { const double y = a[i] * x + s[i]; s[i] = x - a[i] * y; flush(s[i]); x = y; }
        return x;
    }
    void clear() { for (int i = 0; i < N; ++i) s[i] = 0.0; }
};

/// 2x interpolator: one input sample -> two outputs, u[2n] = A0 x[n], u[2n+1] = A1 x[n].
template <int N0, int N1> struct Up2 {
    Chain<N0> c0; Chain<N1> c1;
    void tick(double x, double& u0, double& u1) { u0 = c0.tick(x); u1 = c1.tick(x); }
    void clear() { c0.clear(); c1.clear(); }
};
/// 2x decimator: y[n] = 1/2 (A0{x[2n]} + A1{x[2n-1]}).
template <int N0, int N1> struct Down2 {
    Chain<N0> c0; Chain<N1> c1; double oPrev = 0.0;
    double tick(double x0, double x1) { const double y = 0.5 * (c0.tick(x0) + oPrev); oPrev = c1.tick(x1); flush(oPrev); return y; }
    void clear() { c0.clear(); c1.clear(); oPrev = 0.0; }
};
} // namespace satdetail

/// The static curves, exposed so tests (and a UI curve drawer) use exactly what the audio loop uses.
inline double saturate(int type, double x) {
    switch (type) {
        case 1: { const double a = std::fabs(x); return x / std::cbrt(1.0 + a * a * a); }
        case 2: return x >= 0.0 ? 1.0 - std::exp(-x) : -0.8 * (1.0 - std::exp(x));
        default: return std::tanh(x);
    }
}

class Saturator {
public:
    static constexpr int kMaxChannels = 2;

    void prepare(double sampleRate, int channels = 2) {
        sr_ = sampleRate > 0 ? sampleRate : 48000.0;
        ch_ = std::min(std::max(channels, 1), kMaxChannels);
        setParams(p_);
        reset();
        gSm_ = gT_; mixSm_ = mixT_; outSm_ = outT_;
    }

    void reset() {
        for (auto& c : c_) { c.upA.clear(); c.upB.clear(); c.dnA.clear(); c.dnB.clear(); c.tone = c.dcX = c.dcY = 0.0; }
    }

    void setParams(const SatParams& in) {
        p_ = in;
        p_.driveDb = clampf(p_.driveDb, 0.0f, 36.0f);
        p_.type = std::min(std::max(p_.type, 0), 2);
        p_.bias = clampf(p_.bias, -1.0f, 1.0f);
        p_.toneHz = clampf(p_.toneHz, 1000.0f, 20000.0f);
        p_.mix = clampf(p_.mix, 0.0f, 1.0f);
        p_.outputDb = clampf(p_.outputDb, -24.0f, 12.0f);
        p_.oversample = (p_.oversample >= 4) ? 4 : (p_.oversample >= 2 ? 2 : 1);
        for (auto& c : c_) {
            c.upA.c0.set(satdetail::kStageAA0); c.upA.c1.set(satdetail::kStageAA1); c.dnA.c0.set(satdetail::kStageAA0); c.dnA.c1.set(satdetail::kStageAA1);
            c.upB.c0.set(satdetail::kStageBA0); c.upB.c1.set(satdetail::kStageBA1); c.dnB.c0.set(satdetail::kStageBA0); c.dnB.c1.set(satdetail::kStageBA1);
        }
        const double osr = sr_ * p_.oversample;
        toneOn_ = p_.toneHz < 19900.0f;
        toneC_ = toneOn_ ? 1.0 - std::exp(-6.283185307179586 * static_cast<double>(p_.toneHz) / osr) : 1.0;
        smC_ = std::exp(-1.0 / (0.005 * sr_));
        dcR_ = 1.0 - 6.283185307179586 * 8.0 / sr_;
        gT_ = std::pow(10.0, static_cast<double>(p_.driveDb) / 20.0);
        bias_ = static_cast<double>(p_.bias) * 0.6;
        biasOff_ = saturate(p_.type, bias_);
        mixT_ = static_cast<double>(p_.mix);
        // auto gain: a half-scale peak stays at half scale: norm = 0.5 / |shape(0.5 g + b) - shape(b)|, taken for the louder polarity
        norm_ = 1.0;
        if (p_.autoGain) {
            // RMS-matched: integrate the shaped half-scale sine over one cycle (256 points), remove its DC (the blocker will), and scale so
            // its RMS equals that of the unshaped half-scale sine. Handles asymmetry and heavy clipping, which a peak match does not.
            const int M = 256; double sum = 0, sum2 = 0;
            for (int i = 0; i < M; ++i) { const double v = saturate(p_.type, 0.5 * gT_ * std::sin(6.283185307179586 * (i + 0.5) / M) + bias_) - biasOff_; sum += v; sum2 += v * v; }
            const double mean = sum / M, rms = std::sqrt(std::max(0.0, sum2 / M - mean * mean));
            norm_ = rms > 1e-9 ? (0.5 * 0.70710678118654752) / rms : 1.0;
        }
        outT_ = std::pow(10.0, static_cast<double>(p_.outputDb) / 20.0) * norm_;
    }

    const SatParams& params() const { return p_; }
    /// Round-trip group delay of the oversampler at DC, rounded to whole base-rate samples (0 at 1x or when bypassed).
    int latencySamples() const { return p_.bypass ? 0 : static_cast<int>(std::lround(latency())); }
    double latency() const {
        if (p_.oversample == 1) return 0.0;
        double l = 2.0 * satdetail::kGdA / 2.0;                       // stage A: in + out, at 2x
        if (p_.oversample == 4) l += 2.0 * satdetail::kGdB / 4.0;     // stage B: in + out, at 4x
        return l;
    }

    /// In place. io[c][0..n).
    void process(float* const* io, int channels, int n) {
        if (p_.bypass || n <= 0) return;
        const int C = std::min(channels, ch_);
        const int os = p_.oversample;
        const double toneC = toneC_;
        for (int i = 0; i < n; ++i) {
            gSm_ = gT_ + (gSm_ - gT_) * smC_; mixSm_ = mixT_ + (mixSm_ - mixT_) * smC_; outSm_ = outT_ + (outSm_ - outT_) * smC_;
            const double g = gSm_, mix = mixSm_, outG = outSm_;
            for (int c = 0; c < C; ++c) {
                Chan& ch = c_[c];
                double x = static_cast<double>(io[c][i]);
                if (!std::isfinite(x)) x = 0.0;
                // the nonlinear stage at the oversampled rate: shape, tone, mix, gain
                auto nl = [&](double v) {
                    double w = saturate(p_.type, g * v + bias_) - biasOff_;
                    if (toneOn_) { ch.tone += toneC * (w - ch.tone); satdetail::flush(ch.tone); w = ch.tone; }
                    return (v * (1.0 - mix) + w * mix) * outG;
                };
                double y;
                if (os == 1) y = nl(x);
                else {
                    double a0, a1; ch.upA.tick(x, a0, a1);
                    // nl() carries filter state, so every call is its own statement: C++ leaves argument evaluation order unspecified
                    if (os == 2) { const double n0 = nl(a0); const double n1 = nl(a1); y = ch.dnA.tick(n0, n1); }
                    else {
                        double b0, b1, b2, b3; ch.upB.tick(a0, b0, b1); ch.upB.tick(a1, b2, b3);
                        const double n0 = nl(b0); const double n1 = nl(b1); const double y0 = ch.dnB.tick(n0, n1);
                        const double n2 = nl(b2); const double n3 = nl(b3); const double y1 = ch.dnB.tick(n2, n3);
                        y = ch.dnA.tick(y0, y1);
                    }
                }
                // DC blocker
                const double z = y - ch.dcX + dcR_ * ch.dcY; ch.dcX = y; ch.dcY = z; satdetail::flush(ch.dcY);
                io[c][i] = static_cast<float>(z);
            }
        }
    }

private:
    struct Chan {
        satdetail::Up2<4, 4> upA; satdetail::Up2<2, 2> upB;
        satdetail::Down2<4, 4> dnA; satdetail::Down2<2, 2> dnB;
        double tone = 0, dcX = 0, dcY = 0;
    };
    static float clampf(float v, float lo, float hi) { return v < lo ? lo : (v > hi ? hi : v); }
    SatParams p_{};
    double sr_ = 48000.0;
    int ch_ = 2;
    Chan c_[kMaxChannels];
    bool toneOn_ = false;
    double toneC_ = 1, smC_ = 0, dcR_ = 0.999, gT_ = 1, gSm_ = 1, bias_ = 0, biasOff_ = 0, mixT_ = 1, mixSm_ = 1, outT_ = 1, outSm_ = 1, norm_ = 1;
};

} // namespace lumina::fx
